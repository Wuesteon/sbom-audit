    def test_merge_incremental_keeps_unscanned_findings(self):
        old1 = finding(1, last_seen="2026-02-02")
        old1["bogus"] = "x"
        old2 = finding(2, cls="B")
        del old2["age_days"]  # a previous document missing a FIELDS key must not raise
        previous = {"findings": [old1, old2, {"no": "fingerprint"}]}
        merged, dropped = st.merge(previous, [finding(1)], {}, mode="incremental", today="2026-04-04")
        got = by_fp(merged)
        self.assertTrue(dropped == 0 and set(got) == {fp(1), fp(2)}, "unscanned finding kept")
        self.assertTrue(got[fp(2)]["last_seen"] == "2026-01-01" and got[fp(2)]["age_days"] is None,
                        "carried finding untouched, missing key defaults to None")
        self.assertTrue(all(set(f) == set(findings.FIELDS) for f in merged), "only FIELDS survive")
        self.assertTrue(all("bogus" not in f for f in merged), "unknown keys dropped")
        self.assertTrue(got[fp(1)]["last_seen"] == "2026-04-04", "re-found updated")
        # None / empty previous
        self.assertTrue(st.merge(None, [], {}, mode="full", today="2026-04-04") == ([], 0), "first scan")
        self.assertTrue(len(st.merge({}, [finding(1)], {}, mode="full", today="d")[0]) == 1, "empty doc")
        # deterministic order: class, date descending (None last), fingerprint
        new = [finding(1, cls="B", date="2026-01-01T00:00:00Z"), finding(2, cls="A", date=None),
               finding(3, cls="A", date="2026-01-01T00:00:00Z"), finding(4, cls="A", date="2026-06-01T00:00:00Z"),
               finding(5, cls="A", date="2026-01-01T00:00:00Z")]
        order = [f["fingerprint"] for f in st.merge(None, new, {}, mode="full", today="d")[0]]
        self.assertTrue(order == [fp(4), fp(3), fp(5), fp(2), fp(1)], "sorted by class, date desc, fingerprint")

    def test_merge_full_drops_unfound_open_keeps_decided(self):
        D = st.Decision
        previous = {"findings": [finding(1), finding(2), finding(3), finding(4, status="rotated",
                                                                            rotated_on="2026-01-01"),
                                 finding(5)]}
        decisions = {fp(3): D("accepted", "d", "", None), fp(5): D("false_positive", "d", "", None),
                     fp(4): D("rotated", "d", "", "2026-01-01")}
        merged, dropped = st.merge(previous, [finding(1)], decisions, mode="full", today="2026-04-04")
        got = by_fp(merged)
        self.assertTrue(dropped == 1, "only the undecided unfound open finding is dropped")
        self.assertTrue(set(got) == {fp(1), fp(3), fp(4), fp(5)}, "decided and non-open findings kept")
        self.assertTrue(got[fp(3)]["status"] == "accepted" and got[fp(5)]["status"] == "false_positive",
                        "decisions applied to carried findings")
        merged, dropped = st.merge(previous, [], decisions, mode="incremental", today="2026-04-04")
        self.assertTrue(dropped == 0 and len(merged) == 5, "incremental keeps everything")

    def test_ref_tips_sorted_unique(self):
        repo = make_repo(self.tmp, "r", {"a.txt": "a\n"}, branches=["main", "dev"])
        subprocess.run(["git", "-C", str(repo), "branch", "same-as-dev"], check=True)
        subprocess.run(["git", "-C", str(repo), "tag", "t1"], check=True)
        tips = st.ref_tips(repo)
        self.assertTrue(tips == sorted(set(tips)) and len(tips) == 2, "two distinct tips, sorted")
        self.assertTrue(all(len(t) == 40 for t in tips), "full object names")
        self.assertTrue(st.ref_tips(repo, git=lambda *a: "b\na\nb\n\n") == ["a", "b"], "unique and sorted")

    def test_write_read_atomic_and_hashes(self):
        doc = {"schema": 1, "findings": [{"fingerprint": fp(1)}]}
        path = st.write(self.tmp / "o", doc)
        self.assertTrue(path == self.tmp / "o" / st.SECRETS_JSON and st.read(self.tmp / "o") == doc, "round-trip")
        self.assertTrue(not list((self.tmp / "o").glob("*.tmp")), "no tmp left behind")
        with mock.patch("sbomaudit.cache.os.replace", side_effect=OSError("boom")):
            with self.assertRaises(OSError):
                st.write(self.tmp / "o", {"schema": 2})
        self.assertTrue(st.read(self.tmp / "o") == doc and not list((self.tmp / "o").glob("*.tmp")),
                        "failed replace leaves the old file and no tmp")
        self.assertTrue(st.read(self.tmp / "nowhere") is None, "missing reads as None")
        (self.tmp / "o" / st.SECRETS_JSON).write_text("{nope", encoding="utf-8")
        self.assertTrue(st.read(self.tmp / "o") is None, "unparsable reads as None")
        expected = hashlib.sha256(engine.RULES_PATH.read_bytes() + classify.CLASSES_PATH.read_bytes()).hexdigest()[:16]
        self.assertTrue(st.rules_hash() == expected and len(expected) == 16, "rules hash")
        self.assertTrue(st.plugin_minor() == ".".join(__version__.split(".")[:2]), "derived from __version__")
        self.assertTrue(("reopened_from", "rotated_on") == findings.FIELDS[-2:], "new finding fields come last")

    def test_atomic_write_is_the_shared_pid_named_one(self):
        self.assertIs(st.atomic_write, cache.atomic_write)
        target = self.tmp / "d" / "f.toml"
        with mock.patch("sbomaudit.cache.os.replace", wraps=os.replace) as replace:
            st.atomic_write(target, "a = 1\n")
        self.assertEqual(Path(replace.call_args[0][0]).name, f"f.toml.{os.getpid()}.tmp")
        with mock.patch.object(Path, "write_text", side_effect=OSError("full")):
            with self.assertRaises(OSError):
                st.atomic_write(target, "a = 2\n")
        self.assertEqual(sorted(p.name for p in target.parent.iterdir()), ["f.toml"])
        self.assertEqual(target.read_text(encoding="utf-8"), "a = 1\n")

    def test_add_decision_dates_default_to_the_utc_day(self):
        class Frozen(dt.datetime):
            @classmethod
            def now(cls, tz=None):
                return dt.datetime(2026, 3, 1, 23, 30, tzinfo=dt.timezone.utc)

        with mock.patch.object(st, "dt", SimpleNamespace(datetime=Frozen, timezone=dt.timezone, date=dt.date)):
            st.add_decision(self.tmp, fp(7), "rotated", "late evening")
        got = st.read_decisions(self.tmp)[fp(7)]
        self.assertTrue(got.date == "2026-03-01" and got.rotated_on == "2026-03-01", "the UTC day, not the local one")


