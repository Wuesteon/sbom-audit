"""Persistence for the secrets scan: `secrets.json`, the decisions file, the generated gitleaks ignore
file, incremental state and the reopen rule.

Only `write`, `add_decision` and `write_ignore_file` touch disk, each atomically. Findings are already
redacted when they reach this module; `merge` copies only keys in `findings.FIELDS`.
"""
from __future__ import annotations

import datetime as dt
import hashlib
import json
import tomllib
from dataclasses import dataclass
from pathlib import Path

from .. import __version__, gitio
from ..cache import atomic_write  # noqa: F401  re-exported: guard and report write through store
from . import classify, engine
from .findings import FIELDS

SECRETS_JSON = "secrets.json"
DECISIONS_FILE = "secrets-decisions.toml"
IGNORE_FILE = ".cache/secrets/gitleaks.ignore"
STATUSES = ("open", "rotated", "false_positive", "test_fixture", "accepted")
_IGNORED = ("false_positive", "test_fixture")
_DECISIONS_HEADER = ("# regenerated by sbom-audit on every change: comments and unknown keys are not "
                     "preserved (entries and notes are)")
_IGNORE_HEADER = "# generated by sbom-audit from secrets-decisions.toml — do not edit"
SCHEMA = 1


@dataclass(frozen=True)
class Decision:
    status: str
    date: str
    note: str
    rotated_on: str | None = None


# --------------------------------------------------------------------------- hashes and incremental state

def rules_hash(rules_path: Path = engine.RULES_PATH, classes_path: Path = classify.CLASSES_PATH) -> str:
    return hashlib.sha256(Path(rules_path).read_bytes() + Path(classes_path).read_bytes()).hexdigest()[:16]


def plugin_minor() -> str:
    return ".".join(__version__.split(".")[:2])


def needs_full(previous: dict | None, rules_hash: str, plugin_minor: str) -> str | None:
    """Why the next scan must be a full rescan, or None when an incremental one is enough."""
    if previous is None:
        return "first scan"
    if previous.get("rules_hash") != rules_hash:
        return "rules changed"
    if previous.get("plugin_minor") != plugin_minor:
        return "plugin minor changed"
    return None


def ref_tips(repo: Path, git=gitio.git) -> list[str]:
    """Sorted unique object names of every ref (branches, remote-tracking refs, tags)."""
    out = git(repo, "for-each-ref", "--format=%(objectname)")
    return sorted({line.strip() for line in out.splitlines() if line.strip()})


# --------------------------------------------------------------------------- secrets.json

def read(out: Path) -> dict | None:
    """The previous `secrets.json`, or None when it is missing or unparsable."""
    try:
        doc = json.loads((Path(out) / SECRETS_JSON).read_text(encoding="utf-8"))
    except (OSError, ValueError):
        return None
    return doc if isinstance(doc, dict) else None


def write(out: Path, doc: dict) -> Path:
    return atomic_write(Path(out) / SECRETS_JSON, json.dumps(doc, indent=1, ensure_ascii=False) + "\n")


# --------------------------------------------------------------------------- decisions

def _quote(text: str) -> str:
    """A TOML basic string: JSON escaping, plus the one control character JSON leaves raw."""
    return json.dumps(text, ensure_ascii=False).replace("\x7f", "\\u007f")


def _iso_date(value, label: str) -> str:
    """Strict `YYYY-MM-DD` (a bare TOML date arrives as `datetime.date`); ValueError names `label` only."""
    if isinstance(value, dt.datetime):
        value = None
    elif isinstance(value, dt.date):
        return value.isoformat()
    try:
        if isinstance(value, str) and dt.date.fromisoformat(value).isoformat() == value:
            return value
    except ValueError:
        pass
    raise ValueError(f"{label} must be an ISO date (YYYY-MM-DD)")


def read_decisions(out: Path) -> dict[str, Decision]:
    """The hand-edited decisions file, validated; ValueErrors name the field and fingerprint, never the note."""
    path = Path(out) / DECISIONS_FILE
    if not path.exists():
        return {}
    try:
        text = path.read_text(encoding="utf-8")
    except (OSError, UnicodeDecodeError):
        raise ValueError(f"{DECISIONS_FILE} could not be read") from None
    try:
        table = tomllib.loads(text).get("decisions", {})
    except ValueError:
        raise ValueError(f"{DECISIONS_FILE} is not valid TOML") from None
    if not isinstance(table, dict):
        raise ValueError(f"{DECISIONS_FILE}: 'decisions' must be a table")
    decisions: dict[str, Decision] = {}
    for fingerprint, entry in table.items():
        where = f"{DECISIONS_FILE}, entry {fingerprint}"
        if not isinstance(entry, dict):
            raise ValueError(f"{where}: must be a table")
        status = entry.get("status")
        if status not in STATUSES:
            raise ValueError(f"{where}: status is missing or unknown")
        date = _iso_date(entry.get("date"), f"{where}: date")
        rotated_on = entry.get("rotated_on")
        if status == "rotated":
            rotated_on = _iso_date(rotated_on, f"{where}: rotated_on")
        elif rotated_on is not None:
            raise ValueError(f"{where}: rotated_on is only valid with status rotated")
        decisions[fingerprint] = Decision(status, date, str(entry.get("note", "")), rotated_on)
    return decisions


def _render_decisions(decisions: dict[str, Decision]) -> str:
    blocks = [_DECISIONS_HEADER]
    for fingerprint in sorted(decisions):
        d = decisions[fingerprint]
        lines = [f"[decisions.{_quote(fingerprint)}]", f"status = {_quote(d.status)}",
                 f"date = {_quote(d.date)}", f"note = {_quote(d.note)}"]
        if d.rotated_on is not None:
            lines.append(f"rotated_on = {_quote(d.rotated_on)}")
        blocks.append("\n".join(lines))
    return "\n\n".join(blocks) + "\n"


def add_decision(out: Path, fingerprint: str, status: str, note: str, date: str | None = None,
                 rotated_on: str | None = None) -> Path:
    """Record (or replace) the decision for one fingerprint; the file is rewritten sorted by fingerprint."""
    if status not in STATUSES:
        raise ValueError(f"status must be one of {', '.join(STATUSES)}")
    if not fingerprint or "\n" in fingerprint or "\r" in fingerprint:
        raise ValueError("fingerprint must be a single non-empty line")
    today = dt.datetime.now(dt.timezone.utc).date().isoformat()
    date = _iso_date(date or today, "date")
    if status == "rotated":
        rotated_on = _iso_date(rotated_on or today, "rotated_on")
    elif rotated_on is not None:
        raise ValueError("rotated_on is only valid with status rotated")
    decisions = read_decisions(out)  # raises on an unreadable file instead of overwriting it
    decisions[fingerprint] = Decision(status, date, note, rotated_on)
    return atomic_write(Path(out) / DECISIONS_FILE, _render_decisions(decisions))


def write_ignore_file(out: Path, decisions: dict[str, Decision]) -> Path:
    """The gitleaks ignore file: one fingerprint per line for false positives and test fixtures."""
    lines = [_IGNORE_HEADER, *sorted(f for f, d in decisions.items() if d.status in _IGNORED)]
    return atomic_write(Path(out) / IGNORE_FILE, "\n".join(lines) + "\n")


# --------------------------------------------------------------------------- merge

def _known(finding: dict) -> dict:
    """Exactly the keys in FIELDS; a missing key is None."""
    return {name: finding.get(name) for name in FIELDS}


def _sorted(items: list[dict]) -> list[dict]:
    """By class, then commit date descending (None last), then fingerprint."""
    items.sort(key=lambda f: f["fingerprint"])
    items.sort(key=lambda f: f["date"] or "", reverse=True)
    items.sort(key=lambda f: f["class"] or "")
    return items


def merge(previous: dict | None, new_findings: list[dict], decisions: dict[str, Decision], *,
          mode: str, today: str, scanned_repos: set[str] | None = None) -> tuple[list[dict], int]:
    """Merge the previous document's findings with a scan's; returns (findings, dropped).

    Findings are keyed by bare fingerprint, so the same commit reachable from two repos (forks, shared
    history) collapses to one finding; the remediation is identical. Every output finding has exactly the
    keys in `FIELDS`.

    A decision sets the status (and `rotated_on`). Every other finding's status is derived afresh on each
    scan from the decisions alone: a `value_id` matching a decided-`rotated` finding reopens
    (`status = "open"`, `reopened_from = <that fingerprint>`) when the commit is newer than `rotated_on`,
    otherwise inherits `rotated`; the latest `rotated_on` wins, a tie goes to the smallest fingerprint.
    Removing a decision therefore reverts its finding.

    `incremental` keeps previous findings that were not rescanned. `full` drops a previous finding that is
    open, undecided and not re-found (counted in `dropped`), but only if its repo is in `scanned_repos`
    (None means every repo was scanned); findings of repos that were not scanned are kept as in incremental.
    """
    if mode not in ("full", "incremental"):
        raise ValueError("mode must be 'full' or 'incremental'")
    old: dict[str, dict] = {}
    for raw in (previous or {}).get("findings") or []:
        if isinstance(raw, dict) and raw.get("fingerprint"):
            old[raw["fingerprint"]] = _known(raw)
    new = {f["fingerprint"]: _known(f) for f in new_findings}

    # value_id -> (rotated_on, fingerprint) of the decided-rotated finding; latest wins, then smallest fp
    rotations: dict[str, tuple[str, str]] = {}
    for fingerprint, decision in decisions.items():
        known = new.get(fingerprint) or old.get(fingerprint)
        if decision.status != "rotated" or known is None or not known["value_id"]:
            continue  # a decision for a finding that is in neither scan nor previous document is inert
        best = rotations.get(known["value_id"])
        if best is None or decision.rotated_on > best[0] or (decision.rotated_on == best[0]
                                                             and fingerprint < best[1]):
            rotations[known["value_id"]] = (decision.rotated_on, fingerprint)

    def resolve(f: dict) -> dict:
        decision = decisions.get(f["fingerprint"])
        f["status"], f["rotated_on"], f["reopened_from"] = "open", None, None
        if decision is not None:
            f["status"], f["rotated_on"] = decision.status, decision.rotated_on
        elif f["value_id"] in rotations:
            rotated_on, origin = rotations[f["value_id"]]
            if (f["date"] or "")[:10] > rotated_on:
                f["reopened_from"] = origin
            else:
                f["status"], f["rotated_on"] = "rotated", rotated_on
        return f

    merged: list[dict] = []
    for fingerprint, f in new.items():
        previous_seen = old.get(fingerprint)
        f["first_seen"] = (previous_seen or {}).get("first_seen") or today
        f["last_seen"] = today
        merged.append(resolve(f))

    dropped = 0
    for fingerprint, f in old.items():
        if fingerprint in new:
            continue
        resolve(f)
        if (mode == "full" and f["status"] == "open" and fingerprint not in decisions
                and (scanned_repos is None or f["repo"] in scanned_repos)):
            dropped += 1
            continue
        merged.append(f)
    return _sorted(merged), dropped
