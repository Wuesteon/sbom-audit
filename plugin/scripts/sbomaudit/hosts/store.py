"""Host mode persistence: `hosts.json`, per-host baselines, pinned host keys, `hosts-decisions.toml` and `accept`.

Only `write`, `write_baseline`, `pin_host_keys`, `unpin_host_keys` and `accept` touch disk, each atomically. `write` never
persists raw collector `facts` (apt sources can carry URL credentials): a per-host `facts` key is dropped.

Acceptability is decided by id prefix, not by finding group (`origin:*` is in the "patch" group but is
only recorded). `accept` records the decision; for `change:*`, `lynis-warning:*` and `lynis-index:*` it also
moves the accepted state into the host's baseline.
"""
from __future__ import annotations

import datetime as dt
import json
import re
import tomllib
from dataclasses import dataclass
from pathlib import Path

from ..cache import atomic_write
from .logins import EVENT_ID

HOSTS_JSON = "hosts.json"
HOSTS_MD = "HOSTS.md"
DECISIONS_FILE = "hosts-decisions.toml"
BASELINE_DIR = Path("hosts/baseline")
KNOWN_HOSTS = Path("hosts/known_hosts")
REVIEW_MAX_DAYS = 30
SCHEMA = 1
ALIAS_PREFIX = "sbom-audit-"
_DECISIONS_HEADER = ("# regenerated by sbom-audit on every change: comments and unknown keys are not "
                     "preserved (entries and notes are)")
RECORD_ONLY = ("login:", "origin:", "kev:")


@dataclass(frozen=True)
class Decision:
    host: str
    id: str
    note: str
    date: str
    review_by: str | None = None


# --------------------------------------------------------------------------- hosts.json and baselines

def _read_json(path: Path) -> dict | None:
    try:
        doc = json.loads(path.read_text(encoding="utf-8"))
    except (OSError, ValueError):
        return None
    return doc if isinstance(doc, dict) else None


def _dump(doc: dict) -> str:
    return json.dumps(doc, indent=1, ensure_ascii=False) + "\n"


def read(out: Path) -> dict | None:
    """The previous `hosts.json`, or None when it is missing or unparsable."""
    return _read_json(Path(out) / HOSTS_JSON)


def write(out: Path, doc: dict) -> Path:
    hosts = doc.get("hosts")
    if isinstance(hosts, dict):
        doc = {**doc, "hosts": {name: ({k: v for k, v in h.items() if k != "facts"} if isinstance(h, dict) else h)
                                for name, h in hosts.items()}}
    return atomic_write(Path(out) / HOSTS_JSON, _dump(doc))


def check_host(host: str) -> str:
    """Host names end up in file names and known_hosts aliases: letters, digits, dot, dash, underscore only
    (a comma, `*`, `?` or `!` would turn the alias into a known_hosts pattern)."""
    if not isinstance(host, str) or not re.fullmatch(r"[A-Za-z0-9][A-Za-z0-9._-]*", host):
        raise ValueError(f"invalid host name {host!r}")
    return host


def baseline_path(out: Path, host: str) -> Path:
    return Path(out) / BASELINE_DIR / f"{check_host(host)}.json"


def read_baseline(out: Path, host: str) -> dict | None:
    return _read_json(baseline_path(out, host))


def write_baseline(out: Path, host: str, baseline: dict) -> Path:
    return atomic_write(baseline_path(out, host), _dump(baseline))


# --------------------------------------------------------------------------- decisions

def _quote(text: str) -> str:
    """A TOML basic string: JSON escaping, plus the one control character JSON leaves raw."""
    return json.dumps(text, ensure_ascii=False).replace("\x7f", "\\u007f")


def _iso_date(value, label: str) -> str:
    """Strict `YYYY-MM-DD` (a bare TOML date arrives as `datetime.date`); ValueError names `label` only."""
    if isinstance(value, dt.datetime):
        value = None
    elif isinstance(value, dt.date):
        return value.isoformat()
    try:
        if isinstance(value, str) and dt.date.fromisoformat(value).isoformat() == value:
            return value
    except ValueError:
        pass
    raise ValueError(f"{label} must be an ISO date (YYYY-MM-DD)")


def read_decisions(out: Path) -> dict[tuple[str, str], Decision]:
    """The decisions file, validated; ValueErrors name the field and entry, never the note."""
    path = Path(out) / DECISIONS_FILE
    if not path.exists():
        return {}
    try:
        text = path.read_text(encoding="utf-8")
    except (OSError, UnicodeDecodeError):
        raise ValueError(f"{DECISIONS_FILE} could not be read") from None
    try:
        table = tomllib.loads(text).get("decisions", {})
    except ValueError:
        raise ValueError(f"{DECISIONS_FILE} is not valid TOML") from None
    if not isinstance(table, dict):
        raise ValueError(f"{DECISIONS_FILE}: 'decisions' must be a table")
    decisions: dict[tuple[str, str], Decision] = {}
    for host, entries in table.items():
        if not isinstance(entries, dict):
            raise ValueError(f"{DECISIONS_FILE}, host {host}: must be a table")
        for change_id, entry in entries.items():
            where = f"{DECISIONS_FILE}, entry {host} {change_id}"
            if not isinstance(entry, dict):
                raise ValueError(f"{where}: must be a table")
            date = _iso_date(entry.get("date"), f"{where}: date")
            review_by = entry.get("review_by")
            if review_by is not None:
                review_by = _iso_date(review_by, f"{where}: review_by")
            decisions[(host, change_id)] = Decision(host, change_id, str(entry.get("note", "")), date, review_by)
    return decisions


def _render_decisions(decisions: dict[tuple[str, str], Decision]) -> str:
    blocks = [_DECISIONS_HEADER]
    for key in sorted(decisions):
        d = decisions[key]
        lines = [f"[decisions.{_quote(d.host)}.{_quote(d.id)}]", f"date = {_quote(d.date)}",
                 f"note = {_quote(d.note)}"]
        if d.review_by is not None:
            lines.append(f"review_by = {_quote(d.review_by)}")
        blocks.append("\n".join(lines))
    return "\n\n".join(blocks) + "\n"


def accepted_ids(decisions: dict[tuple[str, str], Decision], host: str, today: dt.date) -> set[str]:
    """The ids accepted for `host`. A `kev:` decision is accepted until its `review_by` date has passed."""
    out: set[str] = set()
    for (h, change_id), d in decisions.items():
        if h != host:
            continue
        if change_id.startswith("kev:") and (d.review_by is None or dt.date.fromisoformat(d.review_by) < today):
            continue
        out.add(change_id)
    return out


# --------------------------------------------------------------------------- accept

def _refusal(change_id: str) -> str | None:
    """Why this kind of finding cannot be accepted, or None when its prefix is acceptable."""
    if change_id.startswith("patch:"):
        return "patch automation can only be fixed, not accepted"
    if change_id.startswith("os:"):
        return "an end-of-life release can only be fixed by upgrading it, not accepted"
    if change_id.startswith("permissive:"):
        return "permissive settings can only be fixed, not accepted"
    if change_id.startswith(("vuln:", "info:kev:")):
        return "vulnerabilities clear by patching, not by accepting"
    if change_id.startswith("hostkey:"):
        return ("re-pin with hosts bootstrap <host>: it shows the new fingerprints and asks for confirmation")
    if change_id.startswith(("vendor:", "info:")):
        return "info findings need no decision"
    if change_id.startswith(("change:", "lynis-warning:", "lynis-index:", *RECORD_ONLY)):
        return None
    return "this kind of finding cannot be accepted"


def _split_change(change_id: str) -> tuple[str, str, str]:
    """`change:<section>:<op><key>` -> (section, op, key); the key may itself contain colons."""
    parts = change_id.split(":", 2)
    if len(parts) != 3 or not parts[1] or len(parts[2]) < 2 or parts[2][0] not in "+-~":
        raise ValueError(f"malformed change-id {change_id!r}")
    return parts[1], parts[2][0], parts[2][1:]


def _accept_change(baseline: dict, host_doc: dict, change_id: str) -> None:
    section, op, key = _split_change(change_id)
    current = (host_doc.get("fingerprint") or {}).get(section)
    unknown = ValueError(f"unknown change-id {change_id!r} (run hosts check first)")
    if not isinstance(current, dict):
        raise unknown
    fingerprint = _dict_at(baseline, "fingerprint")
    base = _dict_at(fingerprint, section)  # an older baseline may predate this section
    if op == "-":
        if key in current:
            raise unknown
        base.pop(key, None)
    else:
        if key not in current:
            raise unknown
        base[key] = current[key]


class _Corrupt(Exception):
    """A baseline that is valid JSON but not shaped like one; `accept` turns it into a ValueError."""


def _dict_at(parent: dict, key: str) -> dict:
    value = parent.setdefault(key, {})
    if not isinstance(value, dict):
        raise _Corrupt(f"{key!r} is not an object")
    return value


def _apply_to_baseline(baseline: dict, host_doc: dict, change_id: str) -> None:
    if change_id.startswith("change:"):
        _accept_change(baseline, host_doc, change_id)
    elif change_id.startswith("lynis-warning:"):
        lynis = _dict_at(baseline, "lynis")
        warnings = lynis.setdefault("warnings", [])
        if not isinstance(warnings, list):
            raise _Corrupt("'warnings' is not a list")
        test_id = change_id.split(":", 1)[1]
        if test_id not in warnings:
            warnings.append(test_id)
    else:
        try:
            index = int(change_id.split(":", 1)[1])
        except ValueError:
            raise ValueError(f"malformed change-id {change_id!r}") from None
        _dict_at(baseline, "lynis")["index"] = index


def _known_key_login(host_doc: dict, change_id: str) -> bool:
    """`login:<user>/<fp>` for a key that is in the host's current `authorized_keys` for that user: a user-and-key
    login decision may be recorded before that key has logged in (a new CI deploy key), never for a key the
    host does not have."""
    if not change_id.startswith("login:") or EVENT_ID.match(change_id):
        return False
    keys = (host_doc.get("fingerprint") or {}).get("authorized_keys")
    return isinstance(keys, dict) and change_id[len("login:"):] in keys


def accept(out: Path, host: str, change_id: str, note: str, review_by: str | None, today: dt.date) -> list[Path]:
    """Validate and record the acceptance of one finding; returns the written paths."""
    reason = _refusal(change_id)
    if reason:
        raise ValueError(reason)
    doc = read(out) or {}
    host_doc = (doc.get("hosts") or {}).get(host)
    if not isinstance(host_doc, dict) or (change_id not in {f.get("id") for f in host_doc.get("findings") or []}
                                          and not _known_key_login(host_doc, change_id)):
        raise ValueError(f"unknown change-id {change_id!r} (run hosts check first)")
    if change_id.startswith("kev:"):
        if review_by is None:
            raise ValueError("a KEV finding needs --review-by (a date within 30 days)")
        limit = today + dt.timedelta(days=REVIEW_MAX_DAYS)
        if not today < dt.date.fromisoformat(_iso_date(review_by, "review_by")) <= limit:
            raise ValueError(f"review_by must be after {today.isoformat()} and at most {REVIEW_MAX_DAYS} days "
                             f"ahead ({limit.isoformat()})")
    elif review_by is not None:
        raise ValueError("review_by is only valid for a KEV finding")
    decisions = read_decisions(out)  # raises on an unreadable file instead of overwriting it
    baseline = None
    if change_id.startswith(("change:", "lynis-")):
        baseline = read_baseline(out, host)
        if baseline is None:
            raise ValueError(f"no baseline for {host} (run hosts check first)")
        try:
            _apply_to_baseline(baseline, host_doc, change_id)
        except _Corrupt as exc:
            raise ValueError(f"baseline for {host} is corrupt: {exc}") from None
    # decision first: if the baseline write below fails, the decision is on record but the baseline is unchanged,
    # so the next check still reports the finding and repeating the accept completes it; never cleared unrecorded
    decisions[(host, change_id)] = Decision(host, change_id, note, today.isoformat(), review_by)
    written = [atomic_write(Path(out) / DECISIONS_FILE, _render_decisions(decisions))]
    if baseline is not None:
        written.append(write_baseline(out, host, baseline))
    from . import report   # lazy: report imports this module
    report.append_log_accept(out, host, change_id)
    return written


# --------------------------------------------------------------------------- known_hosts

def pin_host_keys(out: Path, host: str, lines: list[str], now: dt.datetime | None = None) -> Path:
    """Rewrite `host`'s entries (alias `sbom-audit-<host>`); the other hosts' entries stay untouched.

    `lines` are `ssh-keyscan` output: the first field (host list) is replaced by the alias. A comment line
    `# sbom-audit-<host> pinned <UTC time>` goes right above them, replaced on every pin: it is part of the
    host's pin hash (`checker.known_hosts_sha`), so re-pinning even the same key counts as a re-pin.
    """
    alias = ALIAS_PREFIX + check_host(host)
    new: list[str] = []
    for line in lines:
        parts = line.split()
        if not parts or parts[0].startswith("#"):
            continue
        if len(parts) < 3:
            raise ValueError("a host key line needs a key type and a key")
        entry = " ".join([alias, *parts[1:]])
        if entry not in new:
            new.append(entry)
    if not new:
        raise ValueError("no host keys to pin")
    path = Path(out) / KNOWN_HOSTS
    try:
        existing = path.read_text(encoding="utf-8").splitlines()
    except FileNotFoundError:
        existing = []
    kept = [line for line in existing if _not_alias(line, alias)]
    stamp = (now or dt.datetime.now(dt.timezone.utc)).astimezone(dt.timezone.utc).strftime("%Y-%m-%dT%H:%M:%S.%fZ")
    return atomic_write(path, "\n".join([*kept, f"# {alias} pinned {stamp}", *new]) + "\n")


def _not_alias(line: str, alias: str) -> bool:
    return bool(line.strip()) and (line.split() or [""])[0] != alias and line.split()[:2] != ["#", alias]


def unpin_host_keys(out: Path, host: str) -> bool:
    """Drop `host`'s pinned lines and its `pinned` comment (`hosts unbootstrap`); True when any were there."""
    alias = ALIAS_PREFIX + check_host(host)
    path = Path(out) / KNOWN_HOSTS
    try:
        existing = path.read_text(encoding="utf-8").splitlines()
    except FileNotFoundError:
        return False
    kept = [line for line in existing if _not_alias(line, alias)]
    if len(kept) == len([line for line in existing if line.strip()]):
        return False
    atomic_write(path, "".join(f"{line}\n" for line in kept))
    return True
